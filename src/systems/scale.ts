// 한 판의 **규모**. 여기 있는 값이 바뀌면 경제 전체를 다시 재야 한다.
//
// **이 파일이 따로 있는 이유** — 이 저장소는 규모 변경으로 두 번 무너졌다.
//   · HT-006 — 스탯 3 → 5. 강화 예산은 그대로인데 쓸 곳이 늘어 상대를 못 따라갔다.
//     `RIVAL_GROWTH` 를 0.45 → 0.32 로 손으로 다시 골랐다.
//   · HT-009 — 경주 12 → 20. 상대가 천장(10)까지 올라가 파산이 11% → 39% 가 됐다.
//
// 두 번 다 원인이 같다. **곡선을 기울기로 적어놨다** — 규모가 바뀌면 기울기를
// 다시 계산해야 하는데 그 재계산을 아무도 안 한다.
// 그래서 여기서는 **끝점으로 적는다.** 경주 수를 바꿔도 곡선의 모양이 유지된다.
//
// `session.ts` 가 `race.ts` 를 import 하므로 역방향은 순환이다.
// 양쪽이 같이 읽어야 해서 별도 파일이다.

/**
 * 한 판의 경주 수. **판 길이가 여기서 나온다** — 경주당 약 25초이므로
 * 20경주면 8분 안팎이다(산술이다. 사람이 재기 전까지 실측이 아니다).
 *
 * 12 였다가 20 이 됐다(HT-009). 12경주 완주가 5분이라 목표 10~20분의 절반이었다.
 * 연출을 늘려 채우지 않는다 — 강제 대기는 이미 판의 26% 이고,
 * 10분을 만들려면 5배로 해야 하는데 그건 `length-from-state-not-content` 가 막는 부풀리기다.
 */
export const RACES = 20;

/** 내 말과 상대의 시작 능력치. 첫 경주가 승부가 되려면 같아야 한다. */
export const RIVAL_START = 3;

/**
 * **마지막 경주의 상대 평균 능력치.** 이 값이 압박 곡선의 전부다.
 *
 * 6.5 는 12경주 시절 `3 + 11 × 0.32 = 6.52` 에서 왔다 — 그 배치에서 파산 11% ·
 * 인기마 승률 34% 가 나왔으므로 **알고 있는 좋은 끝점**이다.
 * 내 말 천장이 10 이므로 여기가 8 을 넘으면 강화로 따라갈 수 없게 된다.
 */
export const RIVAL_END = 6.5;

/**
 * `no` 번째 경주의 상대 평균 능력치. **경주 수에 무관하게 끝점이 같다** —
 * 12경주든 20경주든 마지막 상대는 `RIVAL_END` 다.
 *
 * 이것이 `3 + (no-1) * 0.32` 와 다른 점이고, HT-009 가 고친 것의 전부다.
 */
export function rivalForm(no: number, races: number = RACES): number {
  if (races <= 1) return RIVAL_START;
  const t = Math.min(1, Math.max(0, (no - 1) / (races - 1)));
  return RIVAL_START + t * (RIVAL_END - RIVAL_START);
}
